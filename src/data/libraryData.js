export const generateStackBooks = (seed) => {
  const offset = seed.includes('1') ? 0 : seed.includes('2') ? 18 : 36;
  const slice = ALL_BOOKS.slice(offset, offset + 27);
  if (slice.length < 27) {
    slice.push(...ALL_BOOKS.slice(0, 27 - slice.length));
  }
  return slice.map((b, i) => ({
    id: `${seed}-${i}`,
    img: b.cover,
    title: b.title,
    author: b.author,
    category: b.category
  }));
};

